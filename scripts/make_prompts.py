"""Generate the fixed prompt WAV files.

    python scripts/make_prompts.py
    python scripts/make_prompts.py --force
    python scripts/make_prompts.py --language yo --allow-unverified

The prompt library is text-first: the client falls back to the browser's own
speech synthesis when no WAV exists. Generating WAVs is optional and only
useful when you want identical audio on every device or when the browser has
no suitable voice.

Only English is generated by default because English is the only language this
build claims as verified. Other languages need --allow-unverified and are still
unverified translations.

Windows uses the built-in System.Speech synthesiser. macOS uses `say`. Linux
uses `espeak-ng` or `espeak` if installed.
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from avenza.prompts import PROMPTS, PromptLibrary  # noqa: E402

OUT = ROOT / "web" / "prompts"

SAMPLE_VALUES = {
    "amount_words": "five thousand naira",
    "amount_display": "five thousand naira",
    "recipient": "Aisha Bello",
    "last4": "6789",
    "bank": "GTBank",
    "count": 3,
    "period": "today",
    "summary": "Five thousand naira to Aisha Bello.",
    "reference": "AVZ DEMO 1 2 3",
    "reason": "The bank declined it.",
    "limit": "one million naira",
    "seconds": 10,
    "hint": "Chinedu Okafor",
    "status": "settled",
}


def prompt_text(prompt_id: str, language: str) -> str:
    prompt = PromptLibrary().render(prompt_id, language=language, **SAMPLE_VALUES)
    # The naira sign is not spoken by most synthesisers.
    return prompt.text.replace("₦", "").strip()


def synthesize_windows(items: list[dict[str, str]], voice: str | None) -> None:
    with tempfile.TemporaryDirectory(prefix="avenza-prompts-") as tmp:
        tmp_path = Path(tmp)
        data_path = tmp_path / "items.json"
        script_path = tmp_path / "speak.ps1"
        data_path.write_text(json.dumps(items, ensure_ascii=False), encoding="utf-8")

        voice_line = ""
        if voice:
            escaped = voice.replace("'", "''")
            voice_line = (
                "try { $synth.SelectVoice('" + escaped + "') } "
                "catch { Write-Warning \"voice not found: " + escaped + "\" }\n"
            )

        script_path.write_text(
            "Add-Type -AssemblyName System.Speech\n"
            "$ErrorActionPreference = 'Stop'\n"
            "$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer\n"
            "$synth.Rate = 0\n"
            "$synth.Volume = 100\n"
            + voice_line
            + "$items = Get-Content -Raw -Encoding UTF8 -LiteralPath '"
            + str(data_path).replace("'", "''")
            + "' | ConvertFrom-Json\n"
            "foreach ($item in $items) {\n"
            "  $synth.SetOutputToWaveFile($item.path)\n"
            "  $synth.Speak($item.text)\n"
            "  $synth.SetOutputToNull()\n"
            "}\n"
            "$synth.Dispose()\n",
            encoding="utf-8-sig",
        )

        subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-NonInteractive",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
                str(script_path),
            ],
            check=True,
        )


def synthesize_posix(items: list[dict[str, str]], language: str, voice: str | None) -> None:
    system = platform.system().lower()
    if system == "darwin":
        command = ["say", "-o"]
        suffix: list[str] = []
    else:
        espeak = shutil.which("espeak-ng") or shutil.which("espeak")
        if not espeak:
            raise SystemExit(
                "No synthesiser found. Install espeak-ng, or skip WAV generation: "
                "the PWA falls back to browser speech synthesis."
            )
        command = [espeak, "-w"]
        suffix = ["-v", voice or "en"]

    for item in items:
        target = Path(item["path"])
        subprocess.run(
            command + [str(target), item["text"]] + suffix,
            check=True,
        )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate fixed prompt WAV files.")
    parser.add_argument("--language", default="en", help="prompt language code (default: en)")
    parser.add_argument("--allow-unverified", action="store_true", help="allow non-English languages")
    parser.add_argument("--voice", default=None, help="optional synthesiser voice name")
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument("--dry-run", action="store_true", help="print what would be written")
    args = parser.parse_args(argv)

    language = args.language.strip().lower()
    if language not in PROMPTS:
        print(f"unknown language: {language}", file=sys.stderr)
        return 2
    if language != "en" and not args.allow_unverified:
        print(
            f"{language} is an unverified translation. Re-run with --allow-unverified "
            "if you really want audio for it.",
            file=sys.stderr,
        )
        return 2

    OUT.mkdir(parents=True, exist_ok=True)
    items: list[dict[str, str]] = []
    for prompt_id in sorted(PROMPTS[language]):
        target = OUT / f"{language}-{prompt_id}.wav"
        if target.exists() and not args.force:
            continue
        items.append(
            {
                "path": str(target),
                "text": prompt_text(prompt_id, language),
                "id": prompt_id,
            }
        )

    if not items:
        print(f"nothing to do; {language} prompts already exist in {OUT}")
        return 0

    if args.dry_run:
        for item in items:
            print(f"{Path(item['path']).name}: {item['text']}")
        return 0

    print(f"generating {len(items)} {language} prompt(s) into {OUT}")
    if platform.system().lower() == "windows":
        synthesize_windows(items, args.voice)
    else:
        synthesize_posix(items, language, args.voice)
    print("done. PromptLibrary will now serve these WAV files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
